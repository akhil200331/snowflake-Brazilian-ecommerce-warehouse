USE ROLE ACCOUNTADMIN;
-- Grant database access
GRANT USAGE ON DATABASE ECOM_DWH_DEV
TO ROLE SYSADMIN;

GRANT USAGE ON SCHEMA ECOM_DWH_DEV.RAW_DATA
TO ROLE SYSADMIN;

GRANT CREATE TABLE ON SCHEMA ECOM_DWH_DEV.RAW_DATA
TO ROLE SYSADMIN;

-- Grant access to all existing schemas
GRANT USAGE ON ALL SCHEMAS IN DATABASE ECOM_DWH_DEV
TO ROLE SYSADMIN;

GRANT CREATE TABLE ON ALL SCHEMAS IN DATABASE ECOM_DWH_DEV
TO ROLE SYSADMIN;

GRANT CREATE VIEW ON ALL SCHEMAS IN DATABASE ECOM_DWH_DEV
TO ROLE SYSADMIN;

GRANT CREATE STAGE ON ALL SCHEMAS IN DATABASE ECOM_DWH_DEV
TO ROLE SYSADMIN;

GRANT CREATE FILE FORMAT ON ALL SCHEMAS IN DATABASE ECOM_DWH_DEV
TO ROLE SYSADMIN;

GRANT CREATE SEQUENCE ON ALL SCHEMAS IN DATABASE ECOM_DWH_DEV
TO ROLE SYSADMIN;

-- Automatically grant access to future schemas
GRANT USAGE ON FUTURE SCHEMAS IN DATABASE ECOM_DWH_DEV
TO ROLE SYSADMIN;

GRANT CREATE TABLE ON FUTURE SCHEMAS IN DATABASE ECOM_DWH_DEV
TO ROLE SYSADMIN;

GRANT CREATE VIEW ON FUTURE SCHEMAS IN DATABASE ECOM_DWH_DEV
TO ROLE SYSADMIN;

GRANT CREATE STAGE ON FUTURE SCHEMAS IN DATABASE ECOM_DWH_DEV
TO ROLE SYSADMIN;

GRANT CREATE FILE FORMAT ON FUTURE SCHEMAS IN DATABASE ECOM_DWH_DEV
TO ROLE SYSADMIN;

GRANT CREATE SEQUENCE ON FUTURE SCHEMAS IN DATABASE ECOM_DWH_DEV
TO ROLE SYSADMIN;

-- Grant access to existing and future tables
GRANT SELECT, INSERT, UPDATE, DELETE, TRUNCATE
ON ALL TABLES IN DATABASE ECOM_DWH_DEV
TO ROLE SYSADMIN;

GRANT SELECT, INSERT, UPDATE, DELETE, TRUNCATE
ON FUTURE TABLES IN DATABASE ECOM_DWH_DEV
TO ROLE SYSADMIN;


GRANT USAGE ON FILE FORMAT ECOM_DWH_DEV.LANDING.FF_OLIST_CSV
TO ROLE SYSADMIN;