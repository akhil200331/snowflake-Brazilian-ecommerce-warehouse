use role sysadmin;
use warehouse ECOM_DEV;
use database ECOM_DWH_DEV;

CREATE TABLE IF NOT EXISTS ERROR.REJECTED_RECORDS (
  REJECT_ID     NUMBER AUTOINCREMENT,
  SOURCE_TABLE  VARCHAR,
  BUSINESS_KEY  VARCHAR,
  REJECT_REASON VARCHAR,
  RAW_RECORD    VARIANT,
  REJECTED_AT   TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
);


use schema transformed_data;

CREATE TABLE IF NOT EXISTS CUSTOMERS (
  CUSTOMER_ID        VARCHAR NOT NULL,
  CUSTOMER_UNIQUE_ID VARCHAR NOT NULL,
  ZIP_CODE_PREFIX    VARCHAR(5),
  CITY               VARCHAR,
  STATE              VARCHAR(2),
  _SOURCE_FILE VARCHAR, _BRONZE_LOADED_AT TIMESTAMP_LTZ,
  _SILVER_LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
  PRIMARY KEY (CUSTOMER_ID)
);

CREATE TABLE IF NOT EXISTS SELLERS (
  SELLER_ID       VARCHAR NOT NULL,
  ZIP_CODE_PREFIX VARCHAR(5),
  CITY            VARCHAR,
  STATE           VARCHAR(2),
  _SOURCE_FILE VARCHAR, _BRONZE_LOADED_AT TIMESTAMP_LTZ,
  _SILVER_LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
  PRIMARY KEY (SELLER_ID)
);

CREATE TABLE IF NOT EXISTS PRODUCTS (
  PRODUCT_ID                 VARCHAR NOT NULL,
  PRODUCT_CATEGORY_NAME      VARCHAR,
  PRODUCT_NAME_LENGTH        NUMBER(10,2),
  PRODUCT_DESCRIPTION_LENGTH NUMBER(10,2),
  PRODUCT_PHOTOS_QTY         NUMBER(10,2),
  PRODUCT_WEIGHT_G           NUMBER(10,2),
  PRODUCT_LENGTH_CM          NUMBER(10,2),
  PRODUCT_HEIGHT_CM          NUMBER(10,2),
  PRODUCT_WIDTH_CM           NUMBER(10,2),
  _SOURCE_FILE VARCHAR, _BRONZE_LOADED_AT TIMESTAMP_LTZ,
  _SILVER_LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
  PRIMARY KEY (PRODUCT_ID)
);

CREATE TABLE IF NOT EXISTS CATEGORY_TRANSLATION (
  PRODUCT_CATEGORY_NAME         VARCHAR NOT NULL,
  PRODUCT_CATEGORY_NAME_ENGLISH VARCHAR,
  _SOURCE_FILE VARCHAR, _BRONZE_LOADED_AT TIMESTAMP_LTZ,
  _SILVER_LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
  PRIMARY KEY (PRODUCT_CATEGORY_NAME)
);

CREATE TABLE IF NOT EXISTS ORDERS (
  ORDER_ID              VARCHAR NOT NULL,
  CUSTOMER_ID           VARCHAR NOT NULL,
  ORDER_STATUS          VARCHAR,
  PURCHASE_TS           TIMESTAMP_NTZ,
  APPROVED_TS           TIMESTAMP_NTZ,
  CARRIER_DELIVERY_TS   TIMESTAMP_NTZ,
  CUSTOMER_DELIVERY_TS  TIMESTAMP_NTZ,
  ESTIMATED_DELIVERY_TS TIMESTAMP_NTZ,
  DQ_FLAG               VARCHAR,   -- NULL = clean; otherwise a data-quality warning (row is kept)
  _SOURCE_FILE VARCHAR, _BRONZE_LOADED_AT TIMESTAMP_LTZ,
  _SILVER_LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
  PRIMARY KEY (ORDER_ID)
);
-- For databases where ORDERS was created by the earlier version of this script
ALTER TABLE ORDERS ADD COLUMN IF NOT EXISTS DQ_FLAG VARCHAR;

CREATE TABLE IF NOT EXISTS ORDER_ITEMS (
  ORDER_ID          VARCHAR NOT NULL,
  ORDER_ITEM_ID     NUMBER NOT NULL,
  PRODUCT_ID        VARCHAR,
  SELLER_ID         VARCHAR,
  SHIPPING_LIMIT_TS TIMESTAMP_NTZ,
  PRICE             NUMBER(12,2),
  FREIGHT_VALUE     NUMBER(12,2),
  _SOURCE_FILE VARCHAR, _BRONZE_LOADED_AT TIMESTAMP_LTZ,
  _SILVER_LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
  PRIMARY KEY (ORDER_ID, ORDER_ITEM_ID)
);

CREATE TABLE IF NOT EXISTS ORDER_PAYMENTS (
  ORDER_ID             VARCHAR NOT NULL,
  PAYMENT_SEQUENTIAL   NUMBER NOT NULL,
  PAYMENT_TYPE         VARCHAR,
  PAYMENT_INSTALLMENTS NUMBER,
  PAYMENT_VALUE        NUMBER(12,2),
  _SOURCE_FILE VARCHAR, _BRONZE_LOADED_AT TIMESTAMP_LTZ,
  _SILVER_LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
  PRIMARY KEY (ORDER_ID, PAYMENT_SEQUENTIAL)
);

-- Grain: one row per review per order. Key is (REVIEW_ID, ORDER_ID) because REVIEW_ID repeats across orders.
CREATE TABLE IF NOT EXISTS REVIEWS (
  REVIEW_ID              VARCHAR NOT NULL,
  ORDER_ID               VARCHAR NOT NULL,
  REVIEW_SCORE           NUMBER(1,0),
  REVIEW_COMMENT_TITLE   VARCHAR,
  REVIEW_COMMENT_MESSAGE VARCHAR,
  REVIEW_CREATION_TS     TIMESTAMP_NTZ,
  REVIEW_ANSWER_TS       TIMESTAMP_NTZ,
  _SOURCE_FILE VARCHAR, _BRONZE_LOADED_AT TIMESTAMP_LTZ,
  _SILVER_LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
  PRIMARY KEY (REVIEW_ID, ORDER_ID)
);

-- Grain: one row per zip prefix (aggregated from ~1M coordinate rows)
CREATE TABLE IF NOT EXISTS GEO_ZIP (
  ZIP_CODE_PREFIX  VARCHAR(5) NOT NULL,
  LATITUDE         NUMBER(18,15),   -- average of all coordinates for the zip
  LONGITUDE        NUMBER(18,15),
  CITY             VARCHAR,         -- most frequent city for the zip
  STATE            VARCHAR(2),      -- most frequent state for the zip
  SOURCE_ROW_COUNT NUMBER,          -- how many Bronze rows were aggregated (for reconciliation)
  _SOURCE_FILE VARCHAR, _BRONZE_LOADED_AT TIMESTAMP_LTZ,
  _SILVER_LOADED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
  PRIMARY KEY (ZIP_CODE_PREFIX)
);