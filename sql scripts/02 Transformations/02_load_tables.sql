-- ---------- ORDERS (with data-quality flag; flagged rows are KEPT) ----------
INSERT OVERWRITE INTO SILVER.ORDERS
  (ORDER_ID, CUSTOMER_ID, ORDER_STATUS, PURCHASE_TS, APPROVED_TS, CARRIER_DELIVERY_TS,
   CUSTOMER_DELIVERY_TS, ESTIMATED_DELIVERY_TS, DQ_FLAG, _SOURCE_FILE, _BRONZE_LOADED_AT)
SELECT ORDER_ID, CUSTOMER_ID, ORDER_STATUS, PURCHASE_TS, APPROVED_TS, CARRIER_TS,
       CUSTOMER_TS, ESTIMATED_TS,
       CASE
         WHEN ORDER_STATUS = 'delivered' AND CUSTOMER_TS IS NULL            THEN 'DELIVERED_NO_DELIVERY_DATE'
         WHEN ORDER_STATUS <> 'delivered' AND CUSTOMER_TS IS NOT NULL       THEN 'DELIVERY_DATE_BUT_NOT_DELIVERED'
         WHEN CUSTOMER_TS < PURCHASE_TS                                     THEN 'DELIVERED_BEFORE_PURCHASE'
       END,
       _SOURCE_FILE, _LOADED_AT
FROM (
  SELECT TRIM(ORDER_ID) AS ORDER_ID, TRIM(CUSTOMER_ID) AS CUSTOMER_ID, LOWER(TRIM(ORDER_STATUS)) AS ORDER_STATUS,
         TRY_TO_TIMESTAMP_NTZ(ORDER_PURCHASE_TIMESTAMP)      AS PURCHASE_TS,
         TRY_TO_TIMESTAMP_NTZ(ORDER_APPROVED_AT)             AS APPROVED_TS,
         TRY_TO_TIMESTAMP_NTZ(ORDER_DELIVERED_CARRIER_DATE)  AS CARRIER_TS,
         TRY_TO_TIMESTAMP_NTZ(ORDER_DELIVERED_CUSTOMER_DATE) AS CUSTOMER_TS,
         TRY_TO_TIMESTAMP_NTZ(ORDER_ESTIMATED_DELIVERY_DATE) AS ESTIMATED_TS,
         _SOURCE_FILE, _LOADED_AT
  FROM BRONZE.RAW_ORDERS
  WHERE ORDER_ID IS NOT NULL AND CUSTOMER_ID IS NOT NULL
  QUALIFY ROW_NUMBER() OVER (PARTITION BY TRIM(ORDER_ID) ORDER BY _LOADED_AT DESC, _FILE_ROW_NUMBER DESC) = 1
);

