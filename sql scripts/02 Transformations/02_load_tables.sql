-- ---------- REVIEWS ----------
-- Key is (review_id, order_id): review_id alone repeats across different orders.
-- Score must be 1-5; anything else is rejected.
INSERT OVERWRITE INTO SILVER.REVIEWS
  (REVIEW_ID, ORDER_ID, REVIEW_SCORE, REVIEW_COMMENT_TITLE, REVIEW_COMMENT_MESSAGE,
   REVIEW_CREATION_TS, REVIEW_ANSWER_TS, _SOURCE_FILE, _BRONZE_LOADED_AT)
SELECT TRIM(REVIEW_ID), TRIM(ORDER_ID), TRY_TO_NUMBER(REVIEW_SCORE),
       NULLIF(TRIM(REVIEW_COMMENT_TITLE), ''), NULLIF(TRIM(REVIEW_COMMENT_MESSAGE), ''),
       TRY_TO_TIMESTAMP_NTZ(REVIEW_CREATION_DATE), TRY_TO_TIMESTAMP_NTZ(REVIEW_ANSWER_TIMESTAMP),
       _SOURCE_FILE, _LOADED_AT
FROM BRONZE.RAW_ORDER_REVIEWS
WHERE REVIEW_ID IS NOT NULL AND ORDER_ID IS NOT NULL
  AND TRY_TO_NUMBER(REVIEW_SCORE) BETWEEN 1 AND 5
QUALIFY ROW_NUMBER() OVER (PARTITION BY TRIM(REVIEW_ID), TRIM(ORDER_ID)
                           ORDER BY _LOADED_AT DESC, _FILE_ROW_NUMBER DESC) = 1;

INSERT INTO ERROR.REJECTED_RECORDS (SOURCE_TABLE, BUSINESS_KEY, REJECT_REASON, RAW_RECORD)
SELECT 'RAW_ORDER_REVIEWS', COALESCE(REVIEW_ID, 'NULL') || '|' || COALESCE(ORDER_ID, 'NULL'),
       'NULL review_id/order_id or review_score not between 1 and 5', OBJECT_CONSTRUCT(*)
FROM BRONZE.RAW_ORDER_REVIEWS
WHERE REVIEW_ID IS NULL OR ORDER_ID IS NULL
   OR NOT COALESCE(TRY_TO_NUMBER(REVIEW_SCORE) BETWEEN 1 AND 5, FALSE);

-- ---------- GEOLOCATION -> one row per zip prefix ----------
-- Average coordinates, most frequent city/state (MODE). Rows with missing or
-- out-of-Brazil coordinates (lat -34..6, lng -75..-28) are rejected.
INSERT OVERWRITE INTO SILVER.GEO_ZIP
  (ZIP_CODE_PREFIX, LATITUDE, LONGITUDE, CITY, STATE, SOURCE_ROW_COUNT, _SOURCE_FILE, _BRONZE_LOADED_AT)
SELECT ZIP, AVG(LAT), AVG(LNG), MODE(CITY), MODE(STATE), COUNT(*), MAX(_SOURCE_FILE), MAX(_LOADED_AT)
FROM (
  SELECT LPAD(TRIM(GEOLOCATION_ZIP_CODE_PREFIX), 5, '0') AS ZIP,
         TRY_TO_DECIMAL(GEOLOCATION_LAT, 18, 15) AS LAT,
         TRY_TO_DECIMAL(GEOLOCATION_LNG, 18, 15) AS LNG,
         LOWER(TRIM(GEOLOCATION_CITY)) AS CITY, UPPER(TRIM(GEOLOCATION_STATE)) AS STATE,
         _SOURCE_FILE, _LOADED_AT
  FROM BRONZE.RAW_GEOLOCATION
  WHERE GEOLOCATION_ZIP_CODE_PREFIX IS NOT NULL
)
WHERE LAT BETWEEN -34 AND 6 AND LNG BETWEEN -75 AND -28
GROUP BY ZIP;

INSERT INTO ERROR.REJECTED_RECORDS (SOURCE_TABLE, BUSINESS_KEY, REJECT_REASON, RAW_RECORD)
SELECT 'RAW_GEOLOCATION', GEOLOCATION_ZIP_CODE_PREFIX,
       'NULL zip, or missing/out-of-Brazil coordinates', OBJECT_CONSTRUCT(*)
FROM BRONZE.RAW_GEOLOCATION
WHERE GEOLOCATION_ZIP_CODE_PREFIX IS NULL
   OR NOT COALESCE(TRY_TO_DECIMAL(GEOLOCATION_LAT, 18, 15) BETWEEN -34 AND 6
               AND TRY_TO_DECIMAL(GEOLOCATION_LNG, 18, 15) BETWEEN -75 AND -28, FALSE);