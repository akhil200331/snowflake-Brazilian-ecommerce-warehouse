USE WAREHOUSE ECOM_DEV;
USE DATABASE ECOM_DWH_DEV;
USE SCHEMA RAW_DATA;

-- A. What are the duplicate reviews?
SELECT COUNT(*) AS rows_total,
       COUNT(DISTINCT REVIEW_ID) AS distinct_review_id,
       COUNT(DISTINCT REVIEW_ID || '|' || ORDER_ID) AS distinct_review_order,
       COUNT(DISTINCT HASH(REVIEW_ID, ORDER_ID, REVIEW_SCORE, REVIEW_COMMENT_TITLE,
             REVIEW_COMMENT_MESSAGE, REVIEW_CREATION_DATE, REVIEW_ANSWER_TIMESTAMP)) AS distinct_full_rows
FROM RAW_ORDER_REVIEWS;

-- B. Orders without items, by status
SELECT o.ORDER_STATUS, COUNT(*) AS cnt
FROM RAW_ORDERS o LEFT JOIN RAW_ORDER_ITEMS i ON o.ORDER_ID = i.ORDER_ID
WHERE i.ORDER_ID IS NULL GROUP BY 1 ORDER BY 2 DESC;

-- C. Categories missing a translation
SELECT DISTINCT p.PRODUCT_CATEGORY_NAME
FROM RAW_PRODUCTS p LEFT JOIN RAW_CATEGORY_TRANSLATION t ON p.PRODUCT_CATEGORY_NAME = t.PRODUCT_CATEGORY_NAME
WHERE t.PRODUCT_CATEGORY_NAME IS NULL AND p.PRODUCT_CATEGORY_NAME IS NOT NULL;

-- D. Date consistency
SELECT 'delivered but no delivery date' AS chk, COUNT(*) AS cnt FROM RAW_ORDERS
  WHERE ORDER_STATUS = 'delivered' AND ORDER_DELIVERED_CUSTOMER_DATE IS NULL
UNION ALL
SELECT 'not delivered but has delivery date', COUNT(*) FROM RAW_ORDERS
  WHERE ORDER_STATUS <> 'delivered' AND ORDER_DELIVERED_CUSTOMER_DATE IS NOT NULL
UNION ALL
SELECT 'delivered before purchase', COUNT(*) FROM RAW_ORDERS
  WHERE TRY_TO_TIMESTAMP_NTZ(ORDER_DELIVERED_CUSTOMER_DATE) < TRY_TO_TIMESTAMP_NTZ(ORDER_PURCHASE_TIMESTAMP);

-- E. Does one customer_unique_id ever have different city/state/zip?
SELECT COUNT(*) AS unique_ids_with_changing_attributes
FROM (SELECT CUSTOMER_UNIQUE_ID FROM RAW_CUSTOMERS GROUP BY 1
      HAVING COUNT(DISTINCT HASH(CUSTOMER_ZIP_CODE_PREFIX, CUSTOMER_CITY, CUSTOMER_STATE)) > 1);

-- F. Geolocation zip shape
SELECT MIN(LENGTH(GEOLOCATION_ZIP_CODE_PREFIX)) AS min_len, MAX(LENGTH(GEOLOCATION_ZIP_CODE_PREFIX)) AS max_len,
       COUNT(DISTINCT GEOLOCATION_ZIP_CODE_PREFIX) AS distinct_zips
FROM RAW_GEOLOCATION;